"""setup_notes.py --check: the anchors row of SETUP.md is not a per-PR edit, and still a measured claim.

The citation check is replaced by a stub here (the real run is test_render_gate_policy's
test_setup_notes_block_matches_this_environment); SETUP.md is a temporary copy.
"""
import importlib.util
import pathlib

import pytest

TOOLS = pathlib.Path(__file__).resolve().parents[1]
SPEC = importlib.util.spec_from_file_location("setup_notes", TOOLS / "setup_notes.py")

BEGIN = "<!-- generated by tools/setup_notes.py --write; do not edit by hand -->"
END = "<!-- end generated -->"


def notes_with(row):
    body = (row + "\n") if row else ""
    return f"| | |\n|---|---|\n{BEGIN}\n{body}{END}\n| `python3 tools/check_env.py` | 5 passed |\n"


@pytest.fixture
def sn(tmp_path, monkeypatch):
    mod = importlib.util.module_from_spec(SPEC)
    SPEC.loader.exec_module(mod)
    monkeypatch.setattr(mod, "NOTES", tmp_path / "SETUP.md")
    monkeypatch.setattr(mod, "installed_versions", lambda: {n: None for n in mod.PACKAGES})
    monkeypatch.setattr(mod, "netcdf_version", lambda prefix=None: None)
    return mod


def run(sn, monkeypatch, committed_row, counts):
    sn.NOTES.write_text(notes_with(committed_row))
    monkeypatch.setattr(sn, "citation_counts", lambda: counts)
    return sn.main(["--check"])


def written_row(sn, monkeypatch, counts):
    sn.NOTES.write_text(notes_with(None))
    monkeypatch.setattr(sn, "citation_counts", lambda: counts)
    assert sn.main(["--write"]) == 0
    return sn.committed_block(sn.NOTES.read_text())[-1]


def test_a_pr_that_adds_anchors_needs_no_edit_of_the_row(sn, monkeypatch):
    """The row written on one tree still passes on a head with more citations (none unresolved)."""
    row = written_row(sn, monkeypatch, (3973, 768, 0))
    assert run(sn, monkeypatch, row, (4147, 809, 0)) == 0


def test_the_row_carries_no_found_or_distinct_count(sn, monkeypatch):
    row = written_row(sn, monkeypatch, (3973, 768, 0))
    assert "3973" not in row and "768" not in row
    assert "0 unresolved" in row


def test_unresolved_citations_on_the_head_fail_the_check(sn, monkeypatch):
    """A committed '0 unresolved' is a claim: a head with an unresolved citation fails it."""
    row = written_row(sn, monkeypatch, (3973, 768, 0))
    assert run(sn, monkeypatch, row, (3974, 768, 1)) == 1


def test_a_wrong_committed_claim_fails_the_check(sn, monkeypatch):
    """A row claiming unresolved citations that the head does not have fails too."""
    row = written_row(sn, monkeypatch, (3973, 768, 2))
    assert "2 unresolved" in row
    assert run(sn, monkeypatch, row, (3973, 770, 0)) == 1


def test_a_typed_count_in_the_row_fails_the_check(sn, monkeypatch):
    """The old form, counts typed into the row, is refused: the row must be the generated one."""
    typed = "| `python3 tools/code_anchors.py check` | 3973 citations, 768 distinct, 0 unresolved |"
    assert run(sn, monkeypatch, typed, (3973, 768, 0)) == 1


def test_a_missing_anchors_row_fails_the_check(sn, monkeypatch):
    """With the citation check runnable here, the block must commit its claim."""
    assert run(sn, monkeypatch, None, (3973, 768, 0)) == 1


def test_an_environment_that_cannot_run_the_check_skips_the_row(sn, monkeypatch):
    row = written_row(sn, monkeypatch, (3973, 768, 0))
    assert run(sn, monkeypatch, row, None) == 0
