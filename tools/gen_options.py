#!/usr/bin/env python3
"""Generate snapy's option code from src/options/*.yaml (O.rst section 3.3).

--out DIR: <module>_members.inc, _read.inc, _pybind.inc (tables with `struct`)
or <module>_rows.hpp (rows-only tables). --check-pyi/--write-pyi: the .pyi
blocks between the BEGIN/END generated markers. Run by CMake and setup.py.
"""
import argparse
import sys
import textwrap
from pathlib import Path

import yaml

TYPES = {"bool": ("bool", "bool"), "int": ("int", "int"),
         "double": ("double", "float"), "string": ("std::string", "str"),
         "list[double]": ("std::vector<double>", "List[float]"),
         "list[string]": ("std::vector<std::string>", "List[str]")}
TRUE_WORDS = ("1", "on", "true", "yes")
FALSE_WORDS = ("", "0", "off", "false", "no")
MARK = "# {} generated by tools/gen_options.py: {}"

# Row columns: name, key (deck key, a/b nested; none: not read), type,
# default, read (fallback: node[key].as<T>(default); if_present; required:
# else throw std::invalid_argument(error); optional: std::optional member),
# read_default ({cpp: expr} or value), alias ({key: scale}), values and
# value_alias ({word: value}) with error, env, env_default, python, report, doc.


def row(d):
    r = dict(read="fallback" if d.get("key") else "none", alias={},
             value_alias={}, python=True, report=True, doc="")
    r.update(d)
    t = TYPES[r["type"]][0]  # KeyError: unknown type
    r["cpp"] = f"std::optional<{t}>" if r["read"] == "optional" else t
    return r


def load_tables(paths):
    tables = []
    for p in paths:
        for d in yaml.safe_load_all(Path(p).read_text()):
            if not d:
                continue
            d = dict(dict(extra_keys={}, args="", doc="", checks=[]), **d)
            d["src"], d["rows"] = Path(p).name, [row(r) for r in d["options"]]
            tables.append(d)
    return tables


def lit(r, v):
    """C++ literal of value v for row r's type."""
    if isinstance(v, dict) and "cpp" in v:
        return v["cpp"]
    t = r["type"]
    if v is None:
        return None
    if t.startswith("list["):
        return "{" + ", ".join(lit({"type": t[5:-1]}, x) for x in v) + "}"
    if t == "string":
        return '"' + str(v).replace("\\", "\\\\").replace('"', '\\"') + '"'
    return {"bool": lambda: "true" if v else "false", "int": lambda: str(int(v)),
            "double": lambda: repr(float(v))}[t]()


def msg(m, value=None):
    """A message: a string, or C++ argument expressions ($value: the value)."""
    if isinstance(m, list):
        return ", ".join(value if x == "$value" and value else x for x in m)
    return lit({"type": "string"}, m)


def doc(text, indent="  "):
    return [f"{indent}//! {x}"
            for x in textwrap.wrap(" ".join(text.split()), 76 - len(indent))]


def node(var, parts):
    return var + "".join(f'["{p}"]' for p in parts)


def members(rows):
    out = []
    for r in rows:
        init = lit(r, r.get("default")) if r["read"] != "optional" else None
        out += (doc(r["doc"]) if r["doc"] else []) + [
            f"  ADD_ARG({r['cpp']}, {r['name']})"
            + (f" = {init};" if init is not None else ";")]
    return out


def emit_members(t):
    out = [f"// generated by tools/gen_options.py from {t['src']}",
           "// NOLINT(build/header_guard)"]
    if t.get("report_title") is not None:
        rows = {r["name"]: r for r in t["rows"]}
        order = t.get("report_order") or [r["name"] for r in t["rows"] if r["report"]]
        out += [" public:", "  void report(std::ostream& os) const {",
                f'    os << "{t["report_title"]}\\n";']
        for i, n in enumerate(order):
            val = (f'fmt::format("{{}}", {n}())'
                   if rows[n]["type"].startswith("list[") else f"{n}()")
            out.append(f'{"    os" if i == 0 else "      "} << "* {n} = " << {val}'
                       ' << "\\n"' + (";" if i == len(order) - 1 else ""))
        out += ["  }", ""]
    return "\n".join(out + members(t["rows"])) + "\n"


def read_row(r, dst):
    """Statements reading row r from `node` into dst."""
    T, parts = TYPES[r["type"]][0], r["key"].split("/")
    n = node("node", parts)
    rd = lit(r, r["read_default"] if r.get("read_default") is not None
             else r.get("default"))
    if r["alias"]:  # aliased keys (e.g. x2min_pi: pi) win over the plain key
        out = []
        for i, (akey, scale) in enumerate(r["alias"].items()):
            an = node("node", parts[:-1] + [akey])
            fac = {"pi": "M_PI"}.get(str(scale), str(scale))
            out += [f"{'} else if' if i else 'if'} ({an}) {{",
                    f"  {dst} = {an}.as<{T}>() * {fac};"]
        return out + ["} else {", f"  {dst} = {n}.as<{T}>({rd});", "}"]
    if r["read"] in ("if_present", "optional"):
        return [f"if ({n}) {dst} = {n}.as<{T}>();"]
    if r["read"] == "required":
        return [f"if ({n}) {{", f"  {dst} = {n}.as<{T}>();", "} else {",
                f"  throw std::invalid_argument({msg(r['error'])});", "}"]
    assert r["read"] == "fallback", f"{r['name']}: read {r['read']}"
    if not (r.get("values") or r["value_alias"]):
        return [f"{dst} = {n}.as<{T}>({rd});"]
    v, groups = f"v_{r['name']}", {}
    out = [f"auto {v} = {n}.as<{T}>({rd});"]
    for word, value in r["value_alias"].items():
        groups.setdefault(value, []).append(str(word))
    for value, words in groups.items():
        cond = " || ".join(f'{v} == "{w}"' for w in words)
        out.append(f'if ({cond}) {v} = "{value}";')
    if r.get("values"):
        cond = " || ".join(f'{v} == "{w}"' for w in r["values"])
        out.append(f"TORCH_CHECK({cond}, {msg(r['error'], v)});")
    return out + [f"{dst} = {v};"]


def env(r):
    dst = f"op.{r['name']}()"
    head = f'if (char const* env = std::getenv("{r["env"]}")) {{'
    if r["type"] == "bool":
        t = " || ".join(f'v == "{w}"' for w in TRUE_WORDS)
        f = " || ".join(f'v == "{w}"' if w else "v.empty()" for w in FALSE_WORDS)
        return [head, "  std::string v(env);", f"  if ({t}) {{",
                f"    {dst} = true;", f"  }} else if ({f}) {{",
                f"    {dst} = false;", "  } else {",
                f'    TORCH_CHECK(false, "{r["env"]} must be 0 or 1, got \'", v, "\'");',
                "  }", "}"]
    assert r["type"] == "string", f"{r['name']}: env rows are bool or string"
    out = [head, f"  {dst} = std::string(env);"]
    if r.get("env_default") is not None:  # unset: this, whatever the deck says
        out += ["} else {", f"  {dst} = {lit(r, r['env_default'])};"]
    return out + ["}"]


def check(c):
    if c.get("throw") == "invalid_argument":
        return [f"if (!({c['cond']}))",
                f"  throw std::invalid_argument({msg(c['message'])});"]
    return [f"TORCH_CHECK({c['cond']}, {msg(c['message'])});"]


def read_body(t):
    """check_keys per sub-path (table order, extra keys first), the rows (a
    nested row only under its sub-map) and the checks after their rows."""
    lists = {}
    for sub, keys in t["extra_keys"].items():
        lists.setdefault(sub or "", []).extend(keys)
    for r in t["rows"]:
        parts = r["key"].split("/") if r.get("key") else []
        for i, p in enumerate(parts):
            if p not in lists.setdefault("/".join(parts[:i]), []):
                lists["/".join(parts[:i])].append(p)
        for akey in r["alias"]:
            if akey not in lists["/".join(parts[:-1])]:
                lists["/".join(parts[:-1])].append(akey)
    body = []
    for sub, keys in lists.items():
        ks = ", ".join(f'"{k}"' for k in keys)
        n = node("node", sub.split("/"))
        body.append(f'if ({n}) check_keys({n}, path + "/{sub}", {{{ks}}});' if sub
                    else f"check_keys(node, path, {{{ks}}});")
    after = {}
    [after.setdefault(c.get("after"), []).append(c) for c in t["checks"]]
    for r in t["rows"]:
        if r.get("key") and r["read"] != "none":
            lines, parts = read_row(r, f"op.{r['name']}()"), r["key"].split("/")
            if len(parts) > 1:  # yaml-cpp cannot index below a missing key
                assert r.get("read_default") is None, f"{r['name']}: nested read_default"
                lines = ([f"if ({node('node', parts[:-1])}) {{"]
                         + ["  " + x for x in lines] + ["}"])
            body += lines
        body += [x for c in after.pop(r["name"], []) for x in check(c)]
    body += [x for c in after.pop(None, []) for x in check(c)]
    assert not after, f"{t['src']}: checks after unknown rows {list(after)}"
    return body


def emit_reader(t):
    args = f", {t['args']}" if t["args"] else ""
    body = read_body(t)
    if t.get("node_error") is not None:
        body = (["if (node) {", f"  TORCH_CHECK(node.IsMap() || node.IsNull(), "
                 f"{msg(t['node_error'])});", "  if (!node.IsNull()) {"]
                + ["    " + x for x in body] + ["  }", "}"])
    for r in t["rows"]:
        body += env(r) if r.get("env") else []
    return "\n".join(
        [f"// generated by tools/gen_options.py from {t['src']}",
         "// NOLINT(build/header_guard)",
         f"inline void read_{t['module']}_rows({t['struct']}& op, YAML::Node const& node,",
         f"                                 std::string const& path{args}) {{"]
        + ["  " + x for x in body] + ["}"]) + "\n"


def emit_rows_header(t):
    name, parts = t["rows_name"], t["yaml_node"].split("/")
    out = [f"// generated by tools/gen_options.py from {t['src']}", "#pragma once",
           "", "// C/C++"] + [f"#include <{h}>" for h in "cmath cstdlib optional string vector".split()]
    for c, h in (("torch", "c10/util/Exception.h"), ("yaml", "yaml-cpp/yaml.h"),
                 ("snap", "snap/input/check_keys.hpp"), ("arg", "snap/add_arg.h")):
        out += ["", f"// {c}", f"#include <{h}>"]
    out += ["", "namespace snap {", ""] + (doc(t["doc"], "") if t["doc"] else [])
    out += [f"struct {name} {{",
            f"  //! deck node `{t['yaml_node']}` present (else every row keeps its "
            "default)", "  ADD_ARG(bool, present) = false;"] + members(t["rows"])
    args = f", {t['args']}" if t["args"] else ""
    out += ["", " public:", "  //! read the rows from the deck root `config`",
            f"  static {name} read(YAML::Node const& config{args}) {{",
            f"    {name} op;", f'    YAML::Node const n0 = config["{parts[0]}"];']
    for i, p in enumerate(parts[1:], 1):  # a missing level leaves it undefined
        out.append(f'    YAML::Node const n{i} = n{i - 1} ? n{i - 1}["{p}"]'
                   " : YAML::Node(YAML::NodeType::Undefined);")
    out += [f"    YAML::Node const node = n{len(parts) - 1};",
            f'    std::string const path = "{t["yaml_node"]}";',
            "    if (node) {", "      op.present() = true;"]
    out += ["      " + x for x in read_body(t)] + ["    }"]
    for r in t["rows"]:
        out += ["    " + x for x in env(r)] if r.get("env") else []
    return "\n".join(out + ["    return op;", "  }", "};", "",
                            "}  // namespace snap", "", "#undef ADD_ARG", ""])


def emit_pybind(t):
    return "\n".join([f"// generated by tools/gen_options.py from {t['src']}"] + [
        f"      .ADD_OPTION({r['cpp']}, snap::{t['struct']}, {r['name']})"
        for r in t["rows"] if r["python"]]) + "\n"


def emit_pyi(t):
    out = ["    " + MARK.format("BEGIN", t["module"])]
    for r in (r for r in t["rows"] if r["python"]):
        pt, n = TYPES[r["type"]][1], r["name"]
        d = (" ".join(r["doc"].split()) if r["doc"] else n.replace("_", " ")).rstrip(".")
        key = f" Deck key `{t['yaml_node']}/{r['key']}`." if r.get("key") else ""
        out += ["    @overload", f"    def {n}(self) -> {pt}:",
                '        """' + "\n        ".join(textwrap.wrap(f"{d}.{key}", 68))
                + '"""', "        ...", "", "    @overload",
                f'    def {n}(self, value: {pt}) -> "{t["pyi"]["cls"]}": ...', ""]
    return "\n".join(out + ["    " + MARK.format("END", t["module"])]) + "\n"


def write(path, text):
    if not (path.exists() and path.read_text() == text):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("tables", nargs="+")
    p.add_argument("--out", help="directory for the generated build files")
    p.add_argument("--root", default=".", help="repository root (for .pyi)")
    p.add_argument("--check-pyi", action="store_true")
    p.add_argument("--write-pyi", action="store_true")
    a = p.parse_args(argv)
    tables, bad = load_tables(a.tables), 0
    for t in tables if a.out else []:
        out, m = Path(a.out), t["module"]
        if t.get("struct"):
            write(out / f"{m}_members.inc", emit_members(t))
            write(out / f"{m}_read.inc", emit_reader(t))
            write(out / f"{m}_pybind.inc", emit_pybind(t))
        else:
            write(out / f"{m}_rows.hpp", emit_rows_header(t))
    for t in (t for t in tables if t.get("pyi") and (a.check_pyi or a.write_pyi)):
        f = Path(a.root) / t["pyi"]["file"]
        text = f.read_text()
        b, e = (text.find(f"    {MARK.format(w, t['module'])}\n") for w in ("BEGIN", "END"))
        assert b >= 0 and e >= 0, f"{f}: no generated block for {t['module']}"
        new = text[:b] + emit_pyi(t) + text[e + len(MARK.format("END", t["module"])) + 5:]
        if a.write_pyi:
            write(f, new)
        elif new != text:
            print(f"{f}: the {t['module']} stub block differs from {t['src']}; "
                  "run tools/gen_options.py --write-pyi", file=sys.stderr)
            bad += 1
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
