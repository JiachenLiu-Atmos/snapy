#!/usr/bin/env python3
"""Generate snapy's option code from the tables in src/options/*.yaml.

One table per module is the single source of each option's deck key, type,
default, environment override, Python binding and documentation (lane O,
O.rst section 3.3). From a table this script emits, into --out:

  <module>_members.inc   ADD_ARG lines and report(), included in the struct
  <module>_read.inc      read_<module>_rows(): check_keys, the deck reads, the
                         cross-option checks and the environment overrides
  <module>_pybind.inc    .ADD_OPTION(...) lines of the pybind11 class
  <module>.rst           the module's documentation page

and the .pyi stub block of each module with a `pyi` entry. The stub blocks
are checked in (IDEs read them without a build) between the markers

  # BEGIN generated by tools/gen_options.py: <module>
  # END generated by tools/gen_options.py: <module>

and `--check-pyi` fails if a checked-in block differs from the table.

A module without `struct` is a rows-only table: the generated header
<module>_rows.hpp declares a standalone struct <Name>Rows with the rows as
members and `static <Name>Rows read(YAML::Node const& config)`; the owning
lane maps it onto its own options struct.

Runs at CMake configure time (CMakeLists.txt) and in setup.py.

  gen_options.py --out DIR TABLE.yaml...
  gen_options.py --check-pyi --root REPO TABLE.yaml...
  gen_options.py --write-pyi --root REPO TABLE.yaml...
"""
import argparse
import sys
import textwrap
from pathlib import Path

import yaml

CPP_TYPE = {
    "bool": "bool",
    "int": "int",
    "double": "double",
    "string": "std::string",
    "list[double]": "std::vector<double>",
    "list[int]": "std::vector<int>",
    "list[string]": "std::vector<std::string>",
}
PY_TYPE = {
    "bool": "bool",
    "int": "int",
    "double": "float",
    "string": "str",
    "list[double]": "List[float]",
    "list[int]": "List[int]",
    "list[string]": "List[str]",
}
TRUE_WORDS = ("1", "on", "true", "yes")
FALSE_WORDS = ("", "0", "off", "false", "no")
BEGIN = "# BEGIN generated by tools/gen_options.py: "
END = "# END generated by tools/gen_options.py: "


class OptionRow:
    """One option: a member, its deck key, default and override."""

    def __init__(self, d):
        self.name = d["name"]
        self.key = d.get("key")  # None: not read from the deck
        self.type = d["type"]
        if self.type not in CPP_TYPE:
            raise ValueError(f"{self.name}: unknown type {self.type}")
        self.default = d.get("default")
        # how the deck is read: fallback  x = node[key].as<T>(default)
        #                       if_present if (node[key]) x = node[key].as<T>()
        #                       required   as if_present, else throw `error`
        #                       optional   std::optional member, if present
        self.read = d.get("read", "fallback" if self.key else "none")
        self.read_default = d.get("read_default")  # {cpp: expr} or a value
        self.alias = d.get("alias") or {}  # {other_key: scale}
        self.values = d.get("values")  # allowed values (after the aliases)
        self.value_alias = d.get("value_alias") or {}  # {word: value}
        self.error = d.get("error")  # message, or C++ message arguments
        self.throw = d.get("throw", "torch")  # torch | invalid_argument
        self.env = d.get("env")  # environment variable overriding the deck
        self.env_default = d.get("env_default")  # unset env: this, not the deck
        self.python = d.get("python", True)
        self.report = d.get("report", True)
        self.doc = d.get("doc", "")

    @property
    def cpp_type(self):
        t = CPP_TYPE[self.type]
        return f"std::optional<{t}>" if self.read == "optional" else t


class ModuleTable:
    """A module's rows, checks and target struct."""

    def __init__(self, d, path):
        self.path = path
        self.module = d["module"]
        self.struct = d.get("struct")  # None: rows-only table
        self.rows_name = d.get("rows_name")
        self.yaml_node = d.get("yaml_node")  # deck path, for docs and reads
        self.check_path = d.get("check_path", self.yaml_node)
        self.node_error = d.get("node_error")
        self.extra_keys = d.get("extra_keys") or {}  # {subpath: [keys]}
        self.args = d.get("args", "")  # extra reader arguments
        self.report_title = d.get("report_title")
        self.report_order = d.get("report_order")
        self.pyi = d.get("pyi")  # {file: python/snapy/x.pyi, cls: Name}
        self.doc = d.get("doc", "")
        self.rows = [OptionRow(r) for r in d["options"]]
        self.checks = d.get("checks") or []
        names = [r.name for r in self.rows]
        if len(set(names)) != len(names):
            raise ValueError(f"{path}: duplicate option names")


def load_tables(paths):
    tables = []
    for p in paths:
        for d in yaml.safe_load_all(Path(p).read_text()):
            if d:
                tables.append(ModuleTable(d, p))
    return tables


# ---------------------------------------------------------------- C++ ----


def cpp_literal(row, value):
    if isinstance(value, dict) and "cpp" in value:
        return value["cpp"]
    if value is None:
        return None
    t = row.type
    if t == "bool":
        return "true" if value else "false"
    if t == "int":
        return str(int(value))
    if t == "double":
        return repr(float(value))
    if t == "string":
        return '"' + str(value).replace("\\", "\\\\").replace('"', '\\"') + '"'
    if t.startswith("list["):
        inner = OptionRow({"name": "_", "type": t[5:-1]})
        return "{" + ", ".join(cpp_literal(inner, v) for v in value) + "}"
    raise ValueError(t)


def cpp_message(msg, value=None):
    """A message: a plain string, or a list of C++ argument expressions in
    which `$value` names the value read."""
    if isinstance(msg, list):
        return ", ".join(value if m == "$value" and value else m for m in msg)
    return cpp_literal(OptionRow({"name": "_", "type": "string"}), msg)


def emit_doc(text, indent="  "):
    width = 80 - len(indent) - 4
    return [f"{indent}//! {line}"
            for line in textwrap.wrap(" ".join(text.split()), width)]


def emit_members(t):
    """ADD_ARG lines (in table order), then report()."""
    out = [f"// generated by tools/gen_options.py from {Path(t.path).name}",
           "// NOLINT(build/header_guard)"]
    if t.report_title is not None:
        rows = {r.name: r for r in t.rows}
        order = t.report_order or [r.name for r in t.rows if r.report]
        out += [" public:", "  void report(std::ostream& os) const {",
                f'    os << "{t.report_title}\\n";']
        for i, name in enumerate(order):
            r = rows[name]
            val = (f'fmt::format("{{}}", {name}())' if r.type.startswith("list[")
                   else f"{name}()")
            lead = "    os" if i == 0 else "      "
            out.append(f'{lead} << "* {name} = " << {val} << "\\n"'
                       + (";" if i == len(order) - 1 else ""))
        out += ["  }", ""]
    for r in t.rows:
        out += emit_doc(r.doc) if r.doc else []
        init = cpp_literal(r, r.default) if r.read != "optional" else None
        out.append(f"  ADD_ARG({r.cpp_type}, {r.name})"
                   + (f" = {init};" if init is not None else ";"))
    return "\n".join(out) + "\n"


def key_path(key):
    return key.split("/")


def node_expr(var, parts):
    return var + "".join(f'["{p}"]' for p in parts)


def emit_read_row(r, var="node", target="op."):
    """Statements reading one row from the module node `var`."""
    T = CPP_TYPE[r.type]
    parts = key_path(r.key)
    n = node_expr(var, parts)
    dst = f"{target}{r.name}()"
    lines = []
    if r.alias:
        # aliased keys (e.g. x2min_pi: pi) win over the plain key
        first = True
        for akey, scale in r.alias.items():
            an = node_expr(var, parts[:-1] + [akey])
            kw = "if" if first else "} else if"
            fac = {"pi": "M_PI"}.get(str(scale), str(scale))
            lines += [f"{kw} ({an}) {{", f"  {dst} = {an}.as<{T}>() * {fac};"]
            first = False
        rd = r.read_default if r.read_default is not None else r.default
        lines += ["} else {", f"  {dst} = {n}.as<{T}>({cpp_literal(r, rd)});",
                  "}"]
        return lines
    if r.read == "fallback":
        rd = r.read_default if r.read_default is not None else r.default
        if r.values or r.value_alias:
            v = f"v_{r.name}"
            lines.append(f"auto {v} = {n}.as<{T}>({cpp_literal(r, rd)});")
            groups = {}
            for word, value in r.value_alias.items():
                groups.setdefault(value, []).append(str(word))
            for value, words in groups.items():
                cond = " || ".join(f'{v} == "{w}"' for w in words)
                lines.append(f'if ({cond}) {v} = "{value}";')
            if r.values:
                cond = " || ".join(f'{v} == "{w}"' for w in r.values)
                msg = r.error or [f'"{r.key} must be one of {", ".join(r.values)}, got \'"',
                                  "$value", "\"'\""]
                lines.append(f"TORCH_CHECK({cond}, {cpp_message(msg, v)});")
            lines.append(f"{dst} = {v};")
        else:
            lines.append(f"{dst} = {n}.as<{T}>({cpp_literal(r, rd)});")
    elif r.read in ("if_present", "optional"):
        lines.append(f"if ({n}) {dst} = {n}.as<{T}>();")
    elif r.read == "required":
        lines += [f"if ({n}) {{", f"  {dst} = {n}.as<{T}>();", "} else {"]
        if r.throw == "invalid_argument":
            lines.append(f"  throw std::invalid_argument({cpp_message(r.error)});")
        else:
            lines.append(f"  TORCH_CHECK(false, {cpp_message(r.error)});")
        lines.append("}")
    else:
        raise ValueError(f"{r.name}: read {r.read}")
    return lines


def emit_env(r, target="op."):
    dst = f"{target}{r.name}()"
    if r.type == "bool":
        t = " || ".join(f'v == "{w}"' for w in TRUE_WORDS)
        f = " || ".join(f'v == "{w}"' if w else "v.empty()" for w in FALSE_WORDS)
        return [f'if (char const* env = std::getenv("{r.env}")) {{',
                "  std::string v(env);",
                f"  if ({t}) {{", f"    {dst} = true;",
                f"  }} else if ({f}) {{", f"    {dst} = false;",
                "  } else {",
                f'    TORCH_CHECK(false, "{r.env} must be 0 or 1, got \'", v, "\'");',
                "  }", "}"]
    if r.type == "string":
        lines = [f'if (char const* env = std::getenv("{r.env}")) {{',
                 f"  {dst} = std::string(env);"]
        if r.env_default is not None:
            # unset: this value, whatever the deck or the caller set
            lines += ["} else {", f"  {dst} = {cpp_literal(r, r.env_default)};"]
        return lines + ["}"]
    raise ValueError(f"{r.name}: env rows are bool or string")


def emit_check(c):
    cond = c["cond"]
    if c.get("throw") == "invalid_argument":
        return [f"if (!({cond}))",
                f"  throw std::invalid_argument({cpp_message(c['message'])});"]
    return [f"TORCH_CHECK({cond}, {cpp_message(c['message'])});"]


def check_key_lists(t):
    """check_keys lists per sub-path, in table order, with extra keys."""
    lists = {}
    for path, keys in t.extra_keys.items():
        lists.setdefault(path or "", []).extend(keys)
    for r in t.rows:
        if not r.key:
            continue
        parts = key_path(r.key)
        for i in range(len(parts)):
            sub = "/".join(parts[:i])
            if parts[i] not in lists.setdefault(sub, []):
                lists[sub].append(parts[i])
        sub = "/".join(parts[:-1])
        for akey in r.alias:
            if akey not in lists[sub]:
                lists[sub].append(akey)
    return lists


def emit_read_body(t, target):
    """Body of the reader on module node `node`: keys, rows, checks."""
    lists = check_key_lists(t)
    body = []
    for sub, keys in lists.items():
        n = node_expr("node", key_path(sub) if sub else [])
        path = "path" + (f' + "/{sub}"' if sub else "")
        ks = ", ".join(f'"{k}"' for k in keys)
        if sub:
            body.append(f"if ({n}) check_keys({n}, {path}, {{{ks}}});")
        else:
            body.append(f"check_keys(node, {path}, {{{ks}}});")
    checks_after = {}
    for c in t.checks:
        checks_after.setdefault(c.get("after"), []).append(c)
    for r in t.rows:
        if r.key and r.read != "none":
            lines = emit_read_row(r, "node", target)
            parts = key_path(r.key)
            if len(parts) > 1:
                # a missing sub-map leaves the row at its default (yaml-cpp
                # cannot index below a missing key of a const node)
                if r.read == "fallback" and r.read_default is not None:
                    raise ValueError(f"{r.name}: nested rows read the default")
                guard = node_expr("node", parts[:-1])
                lines = [f"if ({guard}) {{"] + ["  " + x for x in lines] + ["}"]
            body += lines
        for c in checks_after.pop(r.name, []):
            body += emit_check(c)
    for c in checks_after.pop(None, []):
        body += emit_check(c)
    if checks_after:
        raise ValueError(f"{t.path}: checks after unknown rows {list(checks_after)}")
    return body


def emit_reader(t):
    """read_<module>_rows(op, node, path[, args]): the module's deck reads."""
    impl = t.struct
    args = f", {t.args}" if t.args else ""
    out = [f"// generated by tools/gen_options.py from {Path(t.path).name}",
           "// NOLINT(build/header_guard)",
           f"inline void read_{t.module}_rows({impl}& op, YAML::Node const& node,",
           f"                                 std::string const& path{args}) {{"]
    body = emit_read_body(t, "op.")
    if t.node_error is not None:
        inner = body
        body = ["if (node) {",
                f"  TORCH_CHECK(node.IsMap() || node.IsNull(), {cpp_message(t.node_error)});",
                "  if (!node.IsNull()) {"]
        body += ["    " + line for line in inner] + ["  }", "}"]
    for r in t.rows:
        if r.env:
            body += emit_env(r, "op.")
    out += ["  " + line for line in body] + ["}"]
    return "\n".join(out) + "\n"


def emit_rows_header(t):
    """Rows-only table: a standalone struct and its reader."""
    name = t.rows_name
    out = [f"// generated by tools/gen_options.py from {Path(t.path).name}",
           "#pragma once", "", "// C/C++", "#include <cmath>", "#include <cstdlib>",
           "#include <optional>", "#include <string>", "#include <vector>", "",
           "// torch", "#include <c10/util/Exception.h>", "",
           "// yaml", "#include <yaml-cpp/yaml.h>", "",
           "// snap", "#include <snap/input/check_keys.hpp>", "",
           "// arg", "#include <snap/add_arg.h>", "", "namespace snap {", ""]
    out += emit_doc(t.doc, "") if t.doc else []
    out += [f"struct {name} {{",
            f"  //! deck node `{t.yaml_node}` present (else every row keeps its "
            "default)",
            "  ADD_ARG(bool, present) = false;"]
    for r in t.rows:
        out += emit_doc(r.doc) if r.doc else []
        init = cpp_literal(r, r.default) if r.read != "optional" else None
        out.append(f"  ADD_ARG({r.cpp_type}, {r.name})"
                   + (f" = {init};" if init is not None else ";"))
    args = f", {t.args}" if t.args else ""
    out += ["", " public:",
            f"  //! read the rows from the deck root `config`",
            f"  static {name} read(YAML::Node const& config{args}) {{",
            f"    {name} op;"]
    parts = key_path(t.yaml_node)
    # walk to the module node; a missing level leaves it undefined
    out.append(f'    YAML::Node const n0 = config["{parts[0]}"];')
    for i, part in enumerate(parts[1:], 1):
        out.append(f'    YAML::Node const n{i} = n{i - 1} ? n{i - 1}["{part}"]'
                   " : YAML::Node(YAML::NodeType::Undefined);")
    out.append(f"    YAML::Node const node = n{len(parts) - 1};")
    out.append(f'    std::string const path = "{t.check_path}";')
    body = emit_read_body(t, "op.")
    out += ["    if (node) {", "      op.present() = true;"]
    out += ["      " + line for line in body] + ["    }"]
    for r in t.rows:
        if r.env:
            out += ["    " + line for line in emit_env(r, "op.")]
    out += ["    return op;", "  }", "};", "", "}  // namespace snap", "",
            "#undef ADD_ARG", ""]
    return "\n".join(out)


def emit_pybind(t):
    out = [f"// generated by tools/gen_options.py from {Path(t.path).name}"]
    for r in t.rows:
        if r.python:
            out.append(f"      .ADD_OPTION({r.cpp_type}, snap::{t.struct}, {r.name})")
    return "\n".join(out) + "\n"


# --------------------------------------------------------- Python stub ----


def emit_pyi(t):
    cls = t.pyi["cls"]
    out = [f"    {BEGIN}{t.module}"]
    for r in t.rows:
        if not r.python:
            continue
        pt = PY_TYPE[r.type]
        doc = " ".join(r.doc.split()) if r.doc else r.name.replace("_", " ")
        doc = doc.rstrip(".")
        key = f" Deck key `{t.yaml_node}/{r.key}`." if r.key else ""
        out += ["    @overload",
                f"    def {r.name}(self) -> {pt}:",
                '        """' + "\n        ".join(
                    textwrap.wrap(f"{doc}.{key}", 68)) + '"""',
                "        ...",
                "",
                "    @overload",
                f'    def {r.name}(self, value: {pt}) -> "{cls}": ...',
                ""]
    out.append(f"    {END}{t.module}")
    return "\n".join(out) + "\n"


def splice_pyi(text, t):
    b = text.find(f"    {BEGIN}{t.module}\n")
    e = text.find(f"    {END}{t.module}\n")
    if b < 0 or e < 0:
        raise ValueError(f"{t.pyi['file']}: no generated block for {t.module}")
    e += len(f"    {END}{t.module}\n")
    return text[:b] + emit_pyi(t) + text[e:]


# ------------------------------------------------------------------ rst ----


def emit_rst(t):
    title = f"Options: ``{t.yaml_node}``"
    out = [title, "=" * len(title), ""]
    if t.doc:
        out += [" ".join(t.doc.split()), ""]
    out += [f"Generated by ``tools/gen_options.py`` from "
            f"``src/options/{Path(t.path).name}``.", "",
            ".. list-table::", "   :header-rows: 1", "",
            "   * - key", "     - member", "     - type", "     - default",
            "     - environment", "     - description"]
    for r in t.rows:
        d = r.default
        if isinstance(d, dict):
            d = d.get("cpp")
        out += [f"   * - ``{r.key}``" if r.key else "   * - (not in the deck)",
                f"     - ``{r.name}``", f"     - {r.type}",
                f"     - ``{d}``" if d is not None else "     - (none)",
                f"     - ``{r.env}``" if r.env else "     -",
                f"     - {' '.join(r.doc.split())}" if r.doc else "     -"]
    if t.checks:
        out += ["", "Checks:", ""]
        out += [f"* ``{c['cond']}``" for c in t.checks]
    return "\n".join(out) + "\n"


# ----------------------------------------------------------------- main ----


def write_if_changed(path, text):
    path = Path(path)
    if path.exists() and path.read_text() == text:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("tables", nargs="+")
    p.add_argument("--out", help="directory for the generated build files")
    p.add_argument("--root", default=".", help="repository root (for .pyi)")
    p.add_argument("--check-pyi", action="store_true")
    p.add_argument("--write-pyi", action="store_true")
    a = p.parse_args(argv)
    tables = load_tables(a.tables)
    if a.out:
        out = Path(a.out)
        for t in tables:
            if t.struct:
                write_if_changed(out / f"{t.module}_members.inc", emit_members(t))
                write_if_changed(out / f"{t.module}_read.inc", emit_reader(t))
                write_if_changed(out / f"{t.module}_pybind.inc", emit_pybind(t))
            else:
                write_if_changed(out / f"{t.module}_rows.hpp", emit_rows_header(t))
            write_if_changed(out / "docs" / f"{t.module}.rst", emit_rst(t))
    bad = 0
    for t in tables:
        if not t.pyi or not (a.check_pyi or a.write_pyi):
            continue
        f = Path(a.root) / t.pyi["file"]
        text = f.read_text()
        new = splice_pyi(text, t)
        if a.write_pyi:
            write_if_changed(f, new)
        elif new != text:
            print(f"{f}: the {t.module} stub block differs from "
                  f"{Path(t.path).name}; run tools/gen_options.py --write-pyi",
                  file=sys.stderr)
            bad += 1
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
